// Package dict provides reference dictionaries used by recognizers:
// first names, last names, countries/citizenships and context keywords.
// Dictionaries are intentionally small built-in seeds; the architecture
// allows loading larger external datasets without rewriting recognizers.
package dict

import "strings"

// Dict is a simple case-insensitive set of words.
type Dict struct {
	words map[string]struct{}
}

// New builds a Dict from the given words (lowercased on insert).
func New(words ...string) *Dict {
	d := &Dict{words: make(map[string]struct{}, len(words))}
	for _, w := range words {
		d.words[strings.ToLower(w)] = struct{}{}
	}
	return d
}

// Contains reports whether the lowercased word is in the dictionary.
func (d *Dict) Contains(word string) bool {
	_, ok := d.words[strings.ToLower(word)]
	return ok
}

// Merge adds all words from another dictionary.
func (d *Dict) Merge(other *Dict) {
	for w := range other.words {
		d.words[w] = struct{}{}
	}
}

// Size returns the number of words.
func (d *Dict) Size() int {
	return len(d.words)
}

// Words returns all words in the dictionary.
func (d *Dict) Words() []string {
	out := make([]string, 0, len(d.words))
	for w := range d.words {
		out = append(out, w)
	}
	return out
}

